--  Количество мероприятий за каждый месяца в конуретном году (+)
	SELECT strftime('%m', Дата) AS Месяц, count(Код_мероприятия) AS "Количество мероприятий"
	FROM Мероприятия
	GROUP BY strftime('%Y', Дата), strftime('%m', Дата)
	HAVING strftime('%Y', Дата) like "2026"
	
--  Не льготная, льготная и общая посещаемость за каждый месяц в конкретном году (+)
	SELECT strftime('%m', М.Дата) AS Месяц, SUM(М.Посещаемость) AS "Не льготная посещаемость", SUM(Л.[Льгот пос]) AS "Льготная посещаемость", SUM(М.Посещаемость) + SUM(Л.[Льгот пос]) AS "Общая посещаемость"
	FROM Мероприятия М LEFT JOIN (
									SELECT Код_мероприятия, SUM(Количество) AS "Льгот пос"
									FROM Льготная_посещаемость
									GROUP BY Код_мероприятия
									) Л ON М.Код_мероприятия = Л.Код_мероприятия
	GROUP BY strftime('%m.%Y', М.Дата)
	HAVING strftime('%Y', М.Дата) like "2026"
	
--  Льготная посещаемость в каждой льготной категории за конкретный месяц, конкретного года (+)
	SELECT strftime('%m.%Y', М.Дата), К.Название AS "Льготная категория", SUM(К.Количество) AS "Количество"
	FROM Мероприятия М LEFT JOIN (
									SELECT ЛП.Код_мероприятия, ЛК.Название, ЛП.Количество
									FROM Льготные_категории ЛК LEFT JOIN Льготная_посещаемость ЛП ON ЛК.Код_категории = ЛП.Код_категории
									GROUP BY ЛП.Код_мероприятия, ЛК.Название
									) К ON М.Код_мероприятия = К.Код_мероприятия
	WHERE [Льготная категория] IS NOT NULL
	GROUP BY strftime('%m.%Y', М.Дата), К.Название
	HAVING strftime('%Y', М.Дата) like "2026" and strftime('%m', М.Дата) like "11"
	
--  Расход за каждый месяц в конкретном году (+)
	SELECT strftime('%m', М.Дата) AS Месяц, SUM(С.Расходы) AS "Расход"
	FROM Мероприятия М LEFT JOIN (
									SELECT Код_мероприятия, SUM(Затраты) AS Расходы
									FROM Смета
									GROUP BY Код_мероприятия
									) С ON М.Код_мероприятия = С.Код_мероприятия 
	GROUP BY strftime('%m.%Y', М.Дата)
	HAVING strftime('%Y', М.Дата) like "2026"
	
--  Доход за каждый месяц в конкретном году (учитывается, что у каждой льготной категории своя скидка на билет) (+)
	SELECT strftime('%m', М.Дата) AS Месяц, SUM(М.Цена_билета*М.Посещаемость)+SUM(П.[Людей при скидке]*М.Цена_билета) AS Доход
	FROM Мероприятия М LEFT JOIN (
									SELECT ЛП.Код_мероприятия, ЛК.Название, ЛК.[Послабление(%)], ЛП.Количество, ЛП.Номер_записи, SUM(ЛК.[Послабление(%)]*1.0/100*ЛП.Количество) AS "Людей при скидке" 
									FROM Льготные_категории ЛК INNER JOIN Льготная_посещаемость ЛП ON ЛК.Код_категории = ЛП.Код_категории
									GROUP BY ЛП.Код_мероприятия
									) П ON М.Код_мероприятия = П.Код_мероприятия
	GROUP BY strftime('%m.%Y', М.Дата)
	HAVING strftime('%Y', М.Дата) like "2026"
	
--  Получение всех годов мероприятий
	SELECT DISTINCT strftime('%Y', М.Дата) AS Год
	FROM Мероприятия М

--  Получение всех месяцев года
	SELECT DISTINCT strftime('%m', М.Дата) AS Месяц
	FROM Мероприятия М
	WHERE strftime('%Y', М.Дата) like "2026"
